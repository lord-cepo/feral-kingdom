"""Bake one deterministic compatibility fingerprint from the shipped rules, map and roster art manifest."""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    """Run before exporting either client; both builds must ship this generated constant and the same source inputs."""
    files = sorted(p for folder in ['catalogue', 'effects', 'model', 'runtime', 'combat']
                   for p in (ROOT / 'scripts' / folder).rglob('*.gd'))
    files += [ROOT / 'assets/characters/sheets/manifest.json']
    files += sorted((ROOT / 'scripts').rglob('*region_map*.gd'))
    files += [ROOT / 'scripts/network/network_session.gd', ROOT / 'scripts/board/board.gd',
              ROOT / 'scripts/ui/local_match_controller.gd']
    digest = hashlib.sha256(b'guerra-relay-protocol-1\n')
    for path in files:
        digest.update(path.relative_to(ROOT).as_posix().encode() + b'\0' + path.read_bytes().replace(b'\r\n', b'\n') + b'\0')
    target = ROOT / 'scripts/network/network_build.gd'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('## Generated by tools/generate_network_fingerprint.py before client export.\n'
                      'extends RefCounted\nconst GAME_VERSION := "0.1.0"\nconst PROTOCOL_VERSION := 1\n'
                      f'const RULES_HASH := "{digest.hexdigest()}"\n', encoding='utf-8')
    print('Network rules fingerprint:', digest.hexdigest())


if __name__ == '__main__':
    main()
